/**
 * WHAT: Generates the Synthea keep module (GMF v2) that keeps only people with any or all of the chosen conditions.
 * NOT:  Does not choose codes; the caller passes codes read from the Synthea modules (conditions.ts).
 * GOVERNED BY: docs/synthea.md
 * CORRECTNESS: NONE — see docs/findings/no-external-authority.md
 * GOTCHA: Codes are sorted before writing, so the same set clicked in a different order gives the same file and hash.
 */
import { createHash } from 'node:crypto';

export type ChosenCondition = { code: string; display: string };
export type Match = 'any' | 'all';

type ActiveCondition = {
  condition_type: 'Active Condition';
  codes: Array<{ system: 'SNOMED-CT'; code: string; display: string }>;
};
type Combined = { condition_type: 'And' | 'Or'; conditions: ActiveCondition[] };

export type KeepModule = {
  name: string;
  gmf_version: 2;
  remarks: string[];
  states: {
    Initial: {
      type: 'Initial';
      conditional_transition: [
        { transition: 'Keep'; condition: ActiveCondition | Combined },
        { transition: 'Terminal' }
      ];
    };
    Keep: { type: 'Terminal' };
    Terminal: { type: 'Terminal' };
  };
};

export function sortConditions(conditions: ChosenCondition[]): ChosenCondition[] {
  const seen = new Map<string, ChosenCondition>();
  for (const c of conditions) if (!seen.has(c.code)) seen.set(c.code, { code: c.code, display: c.display });
  return [...seen.values()].sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
}

/** Returns null when no condition is chosen: then everyone is kept and no -k flag is passed. */
export function buildKeepModule(conditions: ChosenCondition[], match: Match): KeepModule | null {
  const chosen = sortConditions(conditions);
  if (chosen.length === 0) return null;
  const active = chosen.map(
    (c): ActiveCondition => ({
      condition_type: 'Active Condition',
      codes: [{ system: 'SNOMED-CT', code: c.code, display: c.display }]
    })
  );
  const [only] = active;
  const condition: ActiveCondition | Combined =
    active.length === 1 && only ? only : { condition_type: match === 'all' ? 'And' : 'Or', conditions: active };
  const joiner = match === 'all' ? ' and ' : ' or ';
  return {
    name: `Keep: ${chosen.map((c) => c.display).join(joiner)}`,
    gmf_version: 2,
    remarks: [
      'Generated by Cohort Studio. Keeps a simulated person only if, when the simulation ends,',
      `they have ${match === 'all' ? 'all' : 'at least one'} of these conditions active.`
    ],
    states: {
      Initial: {
        type: 'Initial',
        conditional_transition: [{ transition: 'Keep', condition }, { transition: 'Terminal' }]
      },
      Keep: { type: 'Terminal' },
      Terminal: { type: 'Terminal' }
    }
  };
}

/** The exact bytes written to disk; its hash is what the recipe and manifest record. */
export function keepModuleText(module: KeepModule): string {
  return `${JSON.stringify(module, null, 2)}\n`;
}

export function sha256Hex(text: string | Buffer): string {
  return createHash('sha256').update(text).digest('hex');
}
