/**
 * WHAT: markerList(biomarkers, pack): each Anchor marker with its Anchor system and regions, and what the rule pack does with it; renderMarkerList as Markdown.
 * NOT:  Assigns no system, region or rule itself; it only reads the Anchor artefact and the rule pack and reports where they disagree.
 * GOVERNED BY: DECISIONS.md#d12; DECISIONS.md#d14
 * CORRECTNESS: NONE — see docs/findings/no-external-authority.md
 * GOTCHA: "no rule yet" means the interpretation drops the marker silently today. Closing that needs a reviewed rule, never a default.
 */
import type { SystemId, UnrenderableReason } from '@open-twin/interpretation-contract';
import type { RulePack } from './types.js';

/** The fields of an Anchor artefact biomarker this list reads. */
export interface AnchorMarker {
  biomarker_id: string;
  name_de: string;
  loinc_code: string;
  tier: string;
  system_id: SystemId;
  region_ids: string[];
}

export type MarkerRuleUse =
  | { rule: string; emit: 'state'; system_id: SystemId }
  | { rule: string; emit: 'unrenderable'; reason: UnrenderableReason };

export type MarkerPlacement = 'on-body' | 'off-body' | 'no-rule';

export interface MarkerRow {
  marker: AnchorMarker;
  placement: MarkerPlacement;
  rules: MarkerRuleUse[];
  /** A state rule paints this marker on a system other than the one Anchor gives it. */
  systemDiffers: boolean;
}

export interface MarkerList {
  rows: MarkerRow[];
  /** Rule inputs that name no marker in the artefact. */
  unknownInputs: string[];
}

function useOf(rule: RulePack['rules'][number]): MarkerRuleUse {
  if (rule.emit === 'state') {
    if (!rule.system_id) throw new Error(`rule ${rule.id}: emit=state without system_id`);
    return { rule: rule.id, emit: 'state', system_id: rule.system_id };
  }
  if (!rule.unrenderable_reason) throw new Error(`rule ${rule.id}: emit=unrenderable without reason`);
  return { rule: rule.id, emit: 'unrenderable', reason: rule.unrenderable_reason };
}

export function markerList(biomarkers: readonly AnchorMarker[], pack: RulePack): MarkerList {
  const known = new Set(biomarkers.map((marker) => marker.biomarker_id));
  const uses = new Map<string, MarkerRuleUse[]>();
  const unknown = new Set<string>();

  for (const rule of pack.rules) {
    const use = useOf(rule);
    for (const input of rule.inputs) {
      if (!known.has(input.biomarker_id)) unknown.add(input.biomarker_id);
      uses.set(input.biomarker_id, [...(uses.get(input.biomarker_id) ?? []), use]);
    }
  }

  const rows = [...biomarkers]
    .sort((a, b) => a.biomarker_id.localeCompare(b.biomarker_id))
    .map((marker): MarkerRow => {
      const rules = uses.get(marker.biomarker_id) ?? [];
      const states = rules.filter((use) => use.emit === 'state');
      const placement: MarkerPlacement = states.length > 0 ? 'on-body' : rules.length > 0 ? 'off-body' : 'no-rule';
      return {
        marker,
        placement,
        rules,
        systemDiffers: states.some((use) => use.system_id !== marker.system_id)
      };
    });

  return { rows, unknownInputs: [...unknown].sort() };
}

function ruleCell(row: MarkerRow): string {
  if (row.rules.length === 0) return 'no rule yet';
  return row.rules
    .map((use) =>
      use.emit === 'state' ? `${use.system_id} (\`${use.rule}\`)` : `off the body: ${use.reason} (\`${use.rule}\`)`
    )
    .join('; ');
}

export function renderMarkerList(list: MarkerList, command: string): string {
  const count = (placement: MarkerPlacement) => list.rows.filter((row) => row.placement === placement).length;
  const differs = list.rows.filter((row) => row.systemDiffers).length;

  const lines = [
    '# Anchor marker list',
    '',
    `Generated by \`${command}\` from the Anchor artefact and the rule pack. Do not edit by hand.`,
    '',
    'Each Anchor core marker with the system and regions Anchor gives it (D12), and what the rule',
    'pack does with it: paints it on a system, keeps it off the body with a reason, or has no rule',
    'for it yet. A marker with no rule is dropped by the interpretation without saying so; adding',
    'one needs a reviewed rule. Where a rule paints a marker on a different system than Anchor,',
    'the last column says so; which one is right is a clinical decision.',
    '',
    `- Markers: ${list.rows.length}`,
    `- On the body: ${count('on-body')}`,
    `- Off the body: ${count('off-body')}`,
    `- No rule yet: ${count('no-rule')}`,
    `- Rule system differs from Anchor: ${differs}`,
    '',
    '| Marker | Name | LOINC | Tier | Anchor system | Regions | Rule pack | Differs |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |'
  ];

  for (const row of list.rows) {
    const { marker } = row;
    lines.push(
      `| ${[
        marker.biomarker_id,
        marker.name_de,
        marker.loinc_code,
        marker.tier,
        marker.system_id,
        marker.region_ids.join(', '),
        ruleCell(row),
        row.systemDiffers ? 'yes' : ''
      ].join(' | ')} |`
    );
  }

  return `${lines.join('\n')}\n`;
}
